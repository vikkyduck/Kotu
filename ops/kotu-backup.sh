#!/usr/bin/env bash
# Ночной бэкап: базы Postgres, секреты/конфиги и ФАЙЛЫ приложения.
#
# В бэкапе аудио сеансов и настоящие имена. Копия вне сервера — на компьютере
# владелицы (ops/pull-backup.sh). Ограничение «только РФ» (ARCHITECTURE.md §10)
# владелица 23.09.2026 сняла, но выносить бэкап куда-то ещё — только по её
# решению.
#
# Базы — по дампу в день, дампы НЕ удаляются (правило владелицы 23.09.2026:
# система сама ничего не стирает; о месте — предупреждение в журнал). Файлы —
# не копией в день (аудио весит сотни мегабайт), а так:
#   data/{library,uploads,decks} — зеркало рабочих каталогов (удалённое
#     владелицей из них уходит и отсюда);
#   data/archive — архив файлов (прежние версии и удалённое): только
#     пополняется, уже лежащее никогда не перезаписывается и не удаляется.
# На сервере объект архива — жёсткая ссылка на файл рабочего каталога, и в
# бэкапе они по возможности тоже одна копия (-H, см. ниже), а не две.
# Прежние версии строк — в схеме archive, она в каждом дампе базы.
set -euo pipefail

# Архив, снимки перед деплоем и этот бэкап ничего не удаляют сами — место
# только убывает. Громко в журнал (journalctl -u kotu-backup), пока не поздно:
# в начале — до того, как нехватка места уронит дамп (тогда до конца
# скрипта дело не дошло бы), и ещё раз на выходе, в том числе при сбое, если
# место кончилось по ходу.
LOW_SPACE_WARNED=""
warn_low_space() {
  local free
  free=$(df -P -BG / 2>/dev/null | awk 'NR == 2 { sub(/G$/, "", $4); print $4 }')
  if ! [ "$free" -ge 10 ] 2>/dev/null; then
    [ "$LOW_SPACE_WARNED" = "$free" ] && return 0
    LOW_SPACE_WARNED=$free
    echo "ВНИМАНИЕ: на / свободно ${free:-?} ГБ (меньше 10). Бэкап и архив ничего не удаляют сами — решите, что вынести с сервера" >&2
  fi
  return 0
}
warn_low_space
trap warn_low_space EXIT

STAMP=$(date +%Y-%m-%d)
DB_DIR=/opt/backups/db
FILES_DIR=/opt/backups/files
DATA_DIR=/opt/backups/data
mkdir -p "$DB_DIR" "$FILES_DIR" "$DATA_DIR"

# Базы: pg_dumpall берёт и роли, и все базы (kotu, finance_duck и пр.)
sudo -u postgres pg_dumpall | gzip -9 > "$DB_DIR/all-$STAMP.sql.gz.tmp"
mv "$DB_DIR/all-$STAMP.sql.gz.tmp" "$DB_DIR/all-$STAMP.sql.gz"

# И отдельно сама база kotu в формате, который восстанавливается одной
# командой pg_restore. Дамп всего кластера хорош для «сервер сгорел целиком»,
# но чтобы поднять одну базу на чистой машине, из него приходится выкусывать
# нужный кусок руками — в день аварии это последнее, чем хочется заниматься.
sudo -u postgres pg_dump -Fc kotu > "$DB_DIR/kotu-$STAMP.dump.tmp"
mv "$DB_DIR/kotu-$STAMP.dump.tmp" "$DB_DIR/kotu-$STAMP.dump"

# Секреты и юниты — без них восстановление превращается в археологию.
# Через .tmp, как дампы: pull-backup забирает с --ignore-existing и не берёт
# *.tmp, так что недописанный архив не осядет на Mac навсегда.
tar czf "$FILES_DIR/config-$STAMP.tar.gz.tmp" \
  --ignore-failed-read \
  /opt/kotu/.env /opt/kotu/openai-proxy-ca.pem \
  /etc/systemd/system/kotu*.service \
  /etc/nginx/sites-available 2>/dev/null || true
mv "$FILES_DIR/config-$STAMP.tar.gz.tmp" "$FILES_DIR/config-$STAMP.tar.gz"

# Файлы приложения: книги библиотеки, аудио записей, картинки презентаций.
# В базе лежат только тексты и ссылки — без этих каталогов восстановленная
# платформа осталась бы с пустыми полками.
#
# Шаг 1. Рабочие каталоги: обновить изменённое и убрать удалённое. --existing —
# новых файлов здесь не заводим, их кладёт шаг 2 вместе с архивом. rsync
# (без --inplace) пишет обновлённый файл во временный и переименовывает, так
# что прежний inode — если он уже общий с data/archive — остаётся в архиве.
for d in library uploads decks; do
  [ -d "/opt/kotu/$d" ] || continue
  mkdir -p "$DATA_DIR/$d"
  rsync -a --existing --delete "/opt/kotu/$d/" "$DATA_DIR/$d/"
done

# Шаг 2. Новое — одним вызовом по всем четырём каталогам с -H: новый файл
# рабочего каталога и его объект в архиве (на сервере это одна жёсткая
# ссылка) ложатся в бэкап одной копией. --ignore-existing: уже лежащее в
# бэкапе не перезаписывается никогда — объекты архива по содержимому
# легитимно не меняются, и порча на месте на сервере не должна перетечь сюда.
# --delete здесь нет вовсе: из data/archive не удаляется ничего.
# (Копии, сделанные прежней версией скрипта отдельными вызовами, остаются
# двумя — удалять ради места их не будем.)
rsync -aH --ignore-existing \
  --include='/library/***' --include='/uploads/***' --include='/decks/***' \
  --include='/archive/***' --exclude='*' \
  /opt/kotu/ "$DATA_DIR/"

# Ротации нет: дампы и конфиги не удаляются (раньше — 14 дней). Правило
# владелицы 23.09.2026 — система сама ничего не стирает; когда места станет
# мало, warn_low_space скажет об этом в журнал, а что вынести — решает она.

# Проверка: дамп должен быть непустым, распаковываться и содержать наши
# таблицы. Битый архив, о котором узнаёшь в день аварии, — не бэкап.
SIZE=$(stat -c%s "$DB_DIR/all-$STAMP.sql.gz")
gzip -t "$DB_DIR/all-$STAMP.sql.gz"
[ "$SIZE" -gt 10000 ] || { echo "БЭКАП ПОДОЗРИТЕЛЬНО МАЛ: $SIZE байт" >&2; exit 1; }
zcat "$DB_DIR/all-$STAMP.sql.gz" | grep -q "CREATE TABLE public.documents" || {
  echo "В ДАМПЕ НЕТ ТАБЛИЦ KOTU — проверьте pg_dumpall" >&2; exit 1; }

# Восстановимость проверяем не глазами, а pg_restore: он читает оглавление
# дампа и падает на битом файле.
# Читает файл, а не базу, поэтому от имени root: каталог бэкапов закрыт
# от посторонних, и postgres в него не заглядывает.
pg_restore --list "$DB_DIR/kotu-$STAMP.dump" > /dev/null

DATA_SIZE=$(du -sh "$DATA_DIR" 2>/dev/null | cut -f1)
echo "ok: база $((SIZE/1024)) КБ, файлы $DATA_SIZE"
# Место на диске ещё раз проверит trap на выходе (warn_low_space выше).
