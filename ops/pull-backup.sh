#!/usr/bin/env bash
# Забрать бэкап с сервера на этот компьютер — вторая копия на другом диске.
#
# Зачем: ночной бэкап лежит на том же диске, что и сама платформа. Умрёт
# диск — уйдут и данные, и бэкап. Эта копия разрывает связку.
#
# Что копируется: дампы базы, конфиги и зеркало файлов (аудио сеансов,
# книги, картинки презентаций). Это зона А — настоящие имена и записи.
# Значит: только на ВАШ компьютер, не в облако и не за границу.
#
# Запуск: ./ops/pull-backup.sh   (можно хоть каждый день, копируется только
# то, что изменилось)
set -euo pipefail
SERVER=${SERVER:-root@5.129.198.180}
DEST=${DEST:-"$HOME/kotu-backups"}

# Внимание: зеркало синхронизируется с --delete, поэтому в $DEST нельзя
# держать ничего своего — лишнее будет стёрто. Лог поэтому лежит снаружи.
mkdir -p "$DEST"
echo "==> $(date '+%d.%m.%Y %H:%M') — забираю бэкап с $SERVER в $DEST"
# Сначала всё новое — БЕЗ --delete и одним вызовом: -H держит жёсткие ссылки
# (снимки predeploy/ и архив ссылаются на одно содержимое, без -H каждая
# ссылка приехала бы отдельной копией), и ничего здесь пока не удаляется.
rsync -azH "$SERVER:/opt/backups/" "$DEST/"
# Потом удалённое на сервере — только вне data/archive и predeploy: они и на
# сервере не удаляются, так что их пропажа там — авария (потерян /opt/backups,
# диск), и копия на этом компьютере в такой день не должна исчезнуть следом.
rsync -azH --delete --exclude='/data/archive/' --exclude='/predeploy/' \
  "$SERVER:/opt/backups/" "$DEST/"

echo
echo "==> Что лежит локально:"
du -sh "$DEST"/* 2>/dev/null
LATEST=$(ls -1 "$DEST"/db/all-*.sql.gz 2>/dev/null | tail -1 || true)
if [ -n "$LATEST" ]; then
  gzip -t "$LATEST" && echo "==> Свежий дамп цел: $(basename "$LATEST")"
else
  echo "!!! Дампов базы не видно — проверьте бэкап на сервере" >&2
  exit 1
fi
