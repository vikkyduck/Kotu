#!/usr/bin/env bash
# Забрать бэкап с сервера на этот компьютер — вторая копия на другом диске.
#
# Зачем: ночной бэкап лежит на том же диске, что и сама платформа. Умрёт
# диск — уйдут и данные, и бэкап. Эта копия разрывает связку.
#
# Что копируется: дампы базы, конфиги, архив файлов, снимки перед деплоем и
# зеркало рабочих файлов (аудио сеансов, книги, картинки презентаций). Это
# зона А — настоящие имена и записи. Значит: только на ВАШ компьютер, не в
# облако и не за границу.
#
# Правило владелицы: стирать ничего нельзя. Этот скрипт на компьютере НЕ
# удаляет и НЕ перезаписывает ничего, кроме зеркал data/{library,uploads,decks}
# (они повторяют рабочие каталоги сервера: удалённое владелицей уходит и
# отсюда, но лежит в data/archive). Дампы db/*, конфиги files/*, архив
# data/archive и снимки predeploy/ здесь только пополняются — даже когда на
# сервере их уже нет (сервер чистит старые дампы сам, а здесь они остаются:
# это единственные копии базы и .env вне сервера). Место на этом диске
# убывает — решать, что вынести, владелице.
#
# Запуск: ./ops/pull-backup.sh   (можно хоть каждый день, копируется только
# то, что изменилось)
#
# Проверка без сервера: SERVER=local BACKUPS=<каталог> DEST=<каталог> — тот же
# скрипт берёт «сервер» из локального каталога.
set -euo pipefail
SERVER=${SERVER:-root@5.129.198.180}
BACKUPS=${BACKUPS:-/opt/backups}
DEST=${DEST:-"$HOME/kotu-backups"}
MIRRORS="library uploads decks"

if [ "$SERVER" = local ]; then
  SRC="$BACKUPS"
  on_server() { bash -c "$1"; }
else
  SRC="$SERVER:$BACKUPS"
  on_server() { ssh "$SERVER" "$1"; }
fi

mkdir -p "$DEST"
echo "==> $(date '+%d.%m.%Y %H:%M') — забираю бэкап с $SERVER в $DEST"

# Шаг 1. Всё новое — одним вызовом, БЕЗ --delete и с --ignore-existing: то,
# что уже лежит здесь, не перезаписывается никогда. -H держит жёсткие ссылки
# (снимки predeploy/, архив и зеркала ссылаются на одно содержимое, без -H
# каждая ссылка приехала бы отдельной копией). --ignore-existing важен и для
# архива: его объекты по содержимому легитимно не меняются, и порча объекта
# на сервере не должна перетечь сюда. *.tmp — недописанные дампы ночного
# бэкапа: их место займёт готовый файл.
rsync -azH --ignore-existing --exclude='*.tmp' "$SRC/" "$DEST/"

# Шаг 2. Зеркала рабочих каталогов — изменённое и удалённое. Только если
# сервер жив: есть свежий (не старше 2 суток) непустой дамп kotu и каталог
# архива. Иначе пустой или наполовину потерянный /opt/backups (авария,
# ошибка руками) стёр бы здесь последнюю уцелевшую копию файлов. И каждое
# зеркало — только если его каталог на сервере есть.
q() { printf '%q' "$1"; }
ALIVE=$(on_server "d=$(q "$BACKUPS"); \
  f=\$(find \"\$d/db\" -maxdepth 1 -name 'kotu-*.dump' -size +0 -mtime -2 2>/dev/null | head -n 1); \
  [ -n \"\$f\" ] && [ -d \"\$d/data/archive\" ] && echo yes; \
  for m in $MIRRORS; do [ -d \"\$d/data/\$m\" ] && echo \"mirror \$m\"; done; true" || true)

STALE=0
if printf '%s\n' "$ALIVE" | grep -qx yes; then
  for m in $MIRRORS; do
    if printf '%s\n' "$ALIVE" | grep -qx "mirror $m"; then
      mkdir -p "$DEST/data/$m"
      # Без --inplace: rsync пишет новую версию во временный файл и
      # переименовывает, так что прежний inode (общий с data/archive здесь)
      # остаётся в архиве целым.
      rsync -azH --delete --exclude='*.tmp' "$SRC/data/$m/" "$DEST/data/$m/"
    else
      echo "!!! На сервере нет $BACKUPS/data/$m — зеркало здесь не трогаю" >&2
    fi
  done
else
  STALE=1
  {
    echo "!!! ВНИМАНИЕ: сервер не похож на живой — нет свежего (моложе 2 суток)"
    echo "!!! дампа $BACKUPS/db/kotu-*.dump или каталога $BACKUPS/data/archive."
    echo "!!! Зеркала data/{library,uploads,decks} здесь НЕ синхронизированы: ничего"
    echo "!!! не удалено и не перезаписано, забрано только новое. Проверьте ночной"
    echo "!!! бэкап на сервере (journalctl -u kotu-backup), прежде чем что-то чинить."
  } >&2
fi

echo
echo "==> Что лежит локально:"
du -sh "$DEST"/* 2>/dev/null || true
LATEST=$(ls -1 "$DEST"/db/all-*.sql.gz 2>/dev/null | tail -1 || true)
if [ -n "$LATEST" ]; then
  gzip -t "$LATEST" && echo "==> Последний дамп здесь цел: $(basename "$LATEST")"
else
  echo "!!! Дампов базы не видно — проверьте бэкап на сервере" >&2
  exit 1
fi
# Сервер не прошёл проверку — код 2: в логе launchd и в терминале это видно
# как сбой, хотя здесь ничего не потеряно.
[ "$STALE" -eq 0 ] || exit 2
