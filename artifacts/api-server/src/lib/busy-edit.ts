/**
 * Правки, которые нельзя принимать, пока строку пишет машина.
 *
 * Пока расшифровка в работе (status 'processing'), её segments пишет
 * расшифровщик, а пока лекция составляет план (status 'planning'), план
 * пишет машина. Архив строк считает такие записи промежуточным выводом и
 * версию не сохраняет (archive-sql.ts, capture_row, правило 1): ручная
 * правка этих полей в это время была бы молча затёрта машиной — без следа в
 * архиве. Поэтому такие правки отклоняем (409), а не принимаем, чтобы потом
 * потерять. Прочие поля (название, папка) машина не пишет — их править можно.
 *
 * Фронт такие запросы в этих состояниях не шлёт (редактор текста — только у
 * готовой расшифровки, правка плана — только при plan_ready); проверка здесь
 * — от гонки (открытая вкладка, повтор запроса) и от прямых вызовов API.
 */

export const SEGMENTS_BUSY_MESSAGE =
  "Запись ещё расшифровывается — текст сейчас пишет машина, и правка пропала бы. Дождитесь окончания и поправьте снова";

export const PLAN_BUSY_MESSAGE =
  "План ещё составляется — правка пропала бы. Дождитесь, когда он будет готов, и поправьте снова";

/** Статус расшифровки, при котором её текст (segments) пишет машина. */
export const TRANSCRIPTION_WRITING = "processing";
/** Статус лекции, при котором её план пишет машина. */
export const LECTURE_PLANNING = "planning";

/** Отклонить ли правку расшифровки: меняет segments, пока их пишет машина. */
export function segmentsEditBlocked(status: string, fields: { segments?: unknown }): boolean {
  return status === TRANSCRIPTION_WRITING && fields.segments != null;
}

/** Отклонить ли правку плана лекции: план сейчас пишет машина. */
export function planEditBlocked(status: string): boolean {
  return status === LECTURE_PLANNING;
}
