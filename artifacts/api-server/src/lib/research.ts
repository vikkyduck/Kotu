import { askText, modelFor, pickEffort, type WebSource } from "./codex";

/**
 * Веб-исследование для лекций в режиме "исследование ИИ".
 *
 * Раньше это делал Perplexity по отдельному ключу. Теперь - веб-поиск Codex
 * по подписке (lib/codex.ts): модель обязана сходить в поиск, а ссылки из
 * ответа превращаются в номера [n] со списком источников. Наружу уходит
 * только тема лекции, персональных данных здесь нет.
 */

export type { WebSource };

export interface ResearchResult {
  /** Выжимка по теме со ссылками вида [1], [2] внутри текста. */
  summary: string;
  sources: WebSource[];
}

// Область берётся из самой темы: жёсткое «по психоанализу» уводило в сторону
// любую лекцию на другую тему (19.11.2026).
const SYSTEM = [
  "Ты помогаешь лектору собрать материал по теме лекции.",
  "Ищи веб-поиском столько, сколько нужно для полной и точной картины, и отвечай по-русски",
  "подробной выжимкой: понятия и их разграничения, авторы и школы, ключевые работы и даты,",
  "факты и цифры, спорные места и разные позиции.",
  "Опирайся на надежные источники: научные публикации, первоисточники, профильные издания;",
  "слабые и сомнительные источники помечай.",
  "Каждое утверждение подкрепляй ссылкой на найденный источник по ходу текста.",
].join("\n");

/** Глубина рассуждения при исследовании: high - самая глубокая, какую пропускает мост. */
const EFFORT = pickEffort("EFFORT_RESEARCH", "high");

/** Одно исследование: вопрос -> выжимка с пронумерованными источниками. */
export async function research(query: string): Promise<ResearchResult> {
  const answer = await askText({
    model: modelFor("MODEL_RESEARCH"),
    system: SYSTEM,
    user: query,
    webSearch: true,
    effort: EFFORT,
    verbosity: "high",
  });
  const summary = answer.text.trim();
  if (summary === "") throw new Error("Веб-поиск вернул пустой ответ");
  return { summary, sources: answer.sources };
}
