/**
 * Метки скрытых имён ([[PER1]], [[LOC2]]) в библиотечных копиях старых
 * расшифровок, сделанных со скрытием имён (до 18.11.2026). Человеку в выдаче
 * поиска и цитатах источников они ничего не говорят — показываем так же, как
 * на экране записи. Новых меток платформа не создаёт.
 */
export function hideLabels(text: string): string {
  return text.replace(/\[\[PER\d+\]\]/g, "имя скрыто").replace(/\[\[LOC\d+\]\]/g, "место скрыто");
}
