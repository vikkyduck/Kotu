/**
 * Названия всех работ - книги, записи, лекции, презентации - до 200 знаков.
 * Одно правило на все маршруты и на копии в библиотеке: длинное название
 * обрезается, а не отклоняется.
 */
export const TITLE_MAX = 200;

/** Название из ввода: строка без пробелов по краям, не длиннее TITLE_MAX; не строка - "". */
export function titleFrom(raw: unknown): string {
  return typeof raw === "string" ? raw.trim().slice(0, TITLE_MAX) : "";
}
